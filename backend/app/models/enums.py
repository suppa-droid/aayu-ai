from enum import Enum

class AdminTier(str, Enum):
    FIELD_WORKER = "LEVEL_1_FIELD_WORKER"
    DISTRICT_ADMIN = "LEVEL_2_DISTRICT_ADMIN"
    SYSTEM_ADMIN = "LEVEL_3_SYSTEM_ADMIN"

class ApplicationStatus(str, Enum):
    DRAFT = "DRAFT"
    SUBMITTED = "SUBMITTED"
    DOCUMENT_VERIFIED = "DOCUMENT_VERIFIED"
    FLAGGED_MISMATCH = "FLAGGED_MISMATCH"
    ESCALATED_DISTRICT = "ESCALATED_DISTRICT"
    APPROVED = "APPROVED"
    REJECTED = "REJECTED"
    RENEWAL_DUE = "RENEWAL_DUE"

class EligibilityStatus(str, Enum):
    ELIGIBLE = "ELIGIBLE"
    INELIGIBLE = "INELIGIBLE"
    CONDITIONALLY_ELIGIBLE = "CONDITIONALLY_ELIGIBLE"
    NEEDS_MORE_INFO = "NEEDS_MORE_INFO"

class NotificationChannel(str, Enum):
    WHATSAPP = "WHATSAPP"
    VOICE_IVR = "VOICE_IVR"
    SMS = "SMS"
    FIELD_VISIT = "FIELD_VISIT"

class EscalationReason(str, Enum):
    DOCUMENT_DAMAGED = "DOCUMENT_DAMAGED"
    NAME_MISMATCH = "NAME_MISMATCH"
    APPLICATION_REJECTED = "APPLICATION_REJECTED"
    AGE_PROOF_AMBIGUOUS = "AGE_PROOF_AMBIGUOUS"
    SYSTEM_PIPELINE_ERROR = "SYSTEM_PIPELINE_ERROR"
